import { afterEach, expect, test, vi } from "vitest";
import { cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { TurnSettings } from "../src/components/TurnSettings";
import ProjectPrompt from "../src/components/ProjectPrompt";
import * as api from "../src/lib/conversation";
vi.mock("../src/lib/conversation",async original=>({...await original<typeof api>(),providerModels:vi.fn(),createConversation:vi.fn(),readConversation:vi.fn(),controlConversation:vi.fn()}));
afterEach(()=>{cleanup();vi.resetAllMocks();});
test("live Codex models replace stale workstation suggestions without losing the current or pending choice",async()=>{
 vi.mocked(api.providerModels).mockResolvedValue(["configured-model"]);
 const onChange=vi.fn();const snapshot={id:"settings",busy:false,readOnly:false,provider:"codex",model:"current-model",mode:"plan",models:[{model:"live-model"}]};
 const view=render(<TurnSettings provider="codex" snapshot={snapshot} value={{}} onChange={onChange} disabled={false}/>);
 await waitFor(()=>expect(api.providerModels).toHaveBeenCalledWith("codex"));
 expect(screen.queryByRole("option",{name:"configured-model"})).toBeNull();
 expect(screen.getByRole("option",{name:"live-model"})).toBeTruthy();
 expect(screen.getByRole("option",{name:"current-model"})).toBeTruthy();
 expect(screen.getByRole("option",{name:"Conserver : Plan"})).toBeTruthy();
 fireEvent.change(screen.getByLabelText("Modèle"),{target:{value:"live-model"}});
 expect(onChange).toHaveBeenCalledWith({model:"live-model"});
 view.rerender(<TurnSettings provider="codex" snapshot={{...snapshot,model:"other-model",models:[{model:"other-live"}]}} value={{model:"live-model",mode:"execute"}} onChange={onChange} disabled={false}/>);
 expect((screen.getByLabelText("Modèle") as HTMLSelectElement).value).toBe("__custom__");
 expect((screen.getByLabelText("Identifiant du modèle") as HTMLInputElement).value).toBe("live-model");
 expect((screen.getByLabelText("Mode de conversation") as HTMLSelectElement).value).toBe("execute");
});
test("a compact profile model stays a single menu choice without a custom input or mode explanation",async()=>{
 vi.mocked(api.providerModels).mockResolvedValue([]);
 render(<TurnSettings compact provider="codex" defaultModel="gpt-6-astra" value={{model:"gpt-6-astra",mode:"execute"}} onChange={vi.fn()} disabled={false}/>);
 expect((screen.getByLabelText("Modèle") as HTMLSelectElement).value).toBe("gpt-6-astra");
 expect(screen.queryByLabelText("Identifiant du modèle")).toBeNull();
 expect(screen.getByText(/Choix appliqués à l’envoi/).hasAttribute("hidden")).toBe(true);
});
test("the first project prompt sends model and plan choices once through the controller",async()=>{
 vi.mocked(api.providerModels).mockResolvedValue(["chosen-model"]);
 vi.mocked(api.createConversation).mockResolvedValue({id:"first-turn-options"});
 vi.mocked(api.controlConversation).mockResolvedValue({accepted:true});
 vi.mocked(api.readConversation).mockResolvedValue({id:"first-turn-options",busy:false,readOnly:false});
 render(<ProjectPrompt projectId="p" onCreated={vi.fn()}/>);
 await screen.findByRole("option",{name:"chosen-model"});
 fireEvent.change(screen.getByLabelText("Modèle"),{target:{value:"chosen-model"}});
 fireEvent.change(screen.getByLabelText("Mode de conversation"),{target:{value:"plan"}});
 fireEvent.change(screen.getByLabelText("Prompt libre"),{target:{value:"Plan this work"}});
 fireEvent.click(screen.getByRole("button",{name:"Envoyer"}));
 await waitFor(()=>expect(api.controlConversation).toHaveBeenCalledWith("first-turn-options",{action:"message",message:"Plan this work",model:"chosen-model",mode:"plan"}));
 expect(api.controlConversation).toHaveBeenCalledTimes(1);
});
test("a subsequent Codex message applies the chosen model and execution mode and read-only history disables selectors",async()=>{
 vi.mocked(api.providerModels).mockResolvedValue([]);
 vi.mocked(api.controlConversation).mockResolvedValue({accepted:true});
 vi.mocked(api.readConversation).mockResolvedValue({id:"next-turn-options",provider:"codex",busy:false,readOnly:false,mode:"plan",model:"old-model",models:[{model:"next-model"}]});
 render(<ProjectPrompt projectId="p" runId="next-turn-options" onCreated={vi.fn()}/>);
 await screen.findByRole("option",{name:"next-model"});
 fireEvent.change(screen.getByLabelText("Modèle"),{target:{value:"next-model"}});
 fireEvent.change(screen.getByLabelText("Mode de conversation"),{target:{value:"execute"}});
 fireEvent.change(screen.getByLabelText("Message suivant"),{target:{value:"Implement it"}});
 vi.mocked(api.readConversation).mockResolvedValue({id:"next-turn-options",provider:"codex",busy:false,readOnly:true});
 fireEvent.click(screen.getByRole("button",{name:"Envoyer"}));
 await waitFor(()=>expect(api.controlConversation).toHaveBeenCalledWith("next-turn-options",{action:"message",message:"Implement it",model:"next-model",mode:"execute"}));
 await waitFor(()=>expect(screen.getByLabelText("Suivi de la conversation").textContent).toContain("Historique en lecture seule"));
 expect(screen.queryByRole("group",{name:"Prochain message"})).toBeNull();
 expect(screen.getByLabelText("Options de l’historique")).toBeTruthy();
});
test("custom models remain available when the catalogue fails",async()=>{
 vi.mocked(api.providerModels).mockRejectedValue(new Error("offline"));
 const onChange=vi.fn();
 const view=render(<TurnSettings provider="claude" value={{}} onChange={onChange} disabled={false}/>);
 await screen.findByText(/Catalogue indisponible/);
 fireEvent.change(screen.getByLabelText("Modèle"),{target:{value:"__custom__"}});
 expect(onChange).toHaveBeenCalledWith({model:""});
 view.rerender(<TurnSettings provider="claude" value={{model:""}} onChange={onChange} disabled={false}/>);
 fireEvent.change(screen.getByLabelText("Identifiant du modèle"),{target:{value:"custom-model"}});
 expect(onChange).toHaveBeenCalledWith({model:"custom-model"});
});
