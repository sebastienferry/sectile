const {contextBridge,ipcRenderer}=require('electron')
contextBridge.exposeInMainWorld('localAgent',{
 connect:()=>ipcRenderer.invoke('connect'),
 start:settings=>ipcRenderer.invoke('start',settings),
 saveLog:text=>ipcRenderer.invoke('save-log',text),
 settings:()=>ipcRenderer.invoke('settings'),
 shutdown:()=>ipcRenderer.invoke('shutdown'),
 restart:()=>ipcRenderer.invoke('restart'),
 status:()=>ipcRenderer.invoke('status'),
 chooseRepository:()=>ipcRenderer.invoke('choose-repository'),
 serverTasks:(id,q,launchable=false)=>ipcRenderer.invoke('server-tasks',id,q,launchable),
 launchServerTask:(id,taskID,skillID,prompt)=>ipcRenderer.invoke('launch-server-task',id,taskID,skillID,prompt),
 openTask:id=>ipcRenderer.invoke('open-task',id),
 openPR:url=>ipcRenderer.invoke('open-pr',url),
 createTask:input=>ipcRenderer.invoke('create-task',input),
 project:id=>ipcRenderer.invoke('project',id),
 deployProject:(id,action)=>ipcRenderer.invoke('deploy-project',id,action),
 projects:()=>ipcRenderer.invoke('projects'),
 removeProject:id=>ipcRenderer.invoke('remove-project',id),
 mapProject:mapping=>ipcRenderer.invoke('map-project',mapping),
 clearHistory:()=>ipcRenderer.invoke('clear-history'),
 gitDiff:id=>ipcRenderer.invoke('git-diff',id),
 runs:()=>ipcRenderer.invoke('runs'),
 runResult:id=>ipcRenderer.invoke('run-result',id),
 stop:id=>ipcRenderer.invoke('stop',id),
 detach:()=>ipcRenderer.invoke('detach'),
 attach:id=>ipcRenderer.invoke('attach',id),
 input:data=>ipcRenderer.send('terminal-input',data),
 resize:(cols,rows)=>ipcRenderer.send('terminal-resize',{cols,rows}),
 onOutput:callback=>{const fn=(_,data)=>callback(data);ipcRenderer.on('terminal-output',fn);return()=>ipcRenderer.removeListener('terminal-output',fn)},
})
